// Regenerates app/knowledge/data.ts from the audited knowledge/ JSON files and
// the agent persona. Run from the repo root: node sites-functions/scripts/sync-knowledge.mjs
import { readFileSync, readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..");
const knowledgeDir = join(repoRoot, "knowledge");

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf-8"));
}

const sourceFiles = [];
const documents = [];
for (const name of readdirSync(join(knowledgeDir, "national")).filter((n) => n.endsWith(".json")).sort()) {
  const path = join(knowledgeDir, "national", name);
  sourceFiles.push(path);
  documents.push(readJson(path));
}
for (const name of readdirSync(join(knowledgeDir, "henan")).filter((n) => n.endsWith(".json") && n !== "regions.json").sort()) {
  const path = join(knowledgeDir, "henan", name);
  sourceFiles.push(path);
  const payload = readJson(path);
  if (Array.isArray(payload.documents)) documents.push(...payload.documents);
  else documents.push(payload);
}

const channelsPath = join(knowledgeDir, "official_channels", "channels.json");
const formPath = join(knowledgeDir, "official_channels", "root-wage-platform-form.json");
const regionsPath = join(knowledgeDir, "henan", "regions.json");
const personaPath = join(repoRoot, "backend", "agents", "agent_v1", "persona.md");
sourceFiles.push(channelsPath, formPath, regionsPath, personaPath);

const channels = readJson(channelsPath).channels ?? [];
const formSchema = readJson(formPath);
const regions = readJson(regionsPath);
const persona = readFileSync(personaPath, "utf-8");

const hash = createHash("sha256");
for (const path of sourceFiles.sort()) hash.update(readFileSync(path));
const knowledgeVersion = hash.digest("hex").slice(0, 12);

const banner = "// GENERATED by sites-functions/scripts/sync-knowledge.mjs — do not edit by hand.\n";
const body =
  banner +
  `export const KNOWLEDGE_VERSION = ${JSON.stringify(knowledgeVersion)};\n\n` +
  `export const LEGAL_DOCUMENTS = ${JSON.stringify(documents, null, 1)};\n\n` +
  `export const CHANNELS = ${JSON.stringify(channels, null, 1)};\n\n` +
  `export const FORM_SCHEMA = ${JSON.stringify(formSchema, null, 1)};\n\n` +
  `export const REGIONS = ${JSON.stringify(regions, null, 1)};\n\n` +
  `export const PERSONA = ${JSON.stringify(persona)};\n`;

const target = join(here, "..", "app", "knowledge", "data.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, body, "utf-8");
console.log(`Wrote ${target} (${documents.length} documents, ${channels.length} channels, knowledge ${knowledgeVersion})`);